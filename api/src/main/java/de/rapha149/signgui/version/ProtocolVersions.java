    /**
     * Resolves the NMS bucket id (without Mojang prefix) for a protocol version.
     *
     * @return bucket such as {@code 1_21_R5} or {@code 26_2}, or {@code null} if unsupported
     */
    public static String bucketForProtocol(int protocol) {
        // All 1.8.x share protocol 47; VersionMatcher refines R1/R2/R3 via package / Bukkit version.
        if (in(protocol, R1_8_R1_MIN, R1_8_R3_MAX)) return "1_8_R3";
        if (in(protocol, R1_9_R1_MIN, R1_9_R1_MAX)) return "1_9_R1";
        if (in(protocol, R1_9_R2_MIN, R1_9_R2_MAX)) return "1_9_R2";
        if (in(protocol, R1_10_R1_MIN, R1_10_R1_MAX)) return "1_10_R1";
        if (in(protocol, R1_11_R1_MIN, R1_11_R1_MAX)) return "1_11_R1";
        if (in(protocol, R1_12_R1_MIN, R1_12_R1_MAX)) return "1_12_R1";
        if (in(protocol, R1_13_R1_MIN, R1_13_R1_MAX)) return "1_13_R1";
        if (in(protocol, R1_13_R2_MIN, R1_13_R2_MAX)) return "1_13_R2";
        if (in(protocol, R1_14_R1_MIN, R1_14_R1_MAX)) return "1_14_R1";
        if (in(protocol, R1_15_R1_MIN, R1_15_R1_MAX)) return "1_15_R1";
        if (in(protocol, R1_16_R1_MIN, R1_16_R1_MAX)) return "1_16_R1";
        if (in(protocol, R1_16_R2_MIN, R1_16_R2_MAX)) return "1_16_R2";
        if (in(protocol, R1_16_R3_MIN, R1_16_R3_MAX)) return "1_16_R3";
        if (in(protocol, R1_17_R1_MIN, R1_17_R1_MAX)) return "1_17_R1";
        if (in(protocol, R1_18_R1_MIN, R1_18_R1_MAX)) return "1_18_R1";
        if (in(protocol, R1_18_R2_MIN, R1_18_R2_MAX)) return "1_18_R2";
        if (in(protocol, R1_19_R1_MIN, R1_19_R1_MAX)) return "1_19_R1";
        if (in(protocol, R1_19_R2_MIN, R1_19_R2_MAX)) return "1_19_R2";
        if (in(protocol, R1_19_R3_MIN, R1_19_R3_MAX)) return "1_19_R3";
        if (in(protocol, R1_20_R1_MIN, R1_20_R1_MAX)) return "1_20_R1";
        if (in(protocol, R1_20_R2_MIN, R1_20_R2_MAX)) return "1_20_R2";
        if (in(protocol, R1_20_R3_MIN, R1_20_R3_MAX)) return "1_20_R3";
        if (in(protocol, R1_20_R4_MIN, R1_20_R4_MAX)) return "1_20_R4";
        if (in(protocol, R1_21_R1_MIN, R1_21_R1_MAX)) return "1_21_R1";
        if (in(protocol, R1_21_R2_MIN, R1_21_R2_MAX)) return "1_21_R2";
        if (in(protocol, R1_21_R3_MIN, R1_21_R3_MAX)) return "1_21_R3";
        if (in(protocol, R1_21_R4_MIN, R1_21_R4_MAX)) return "1_21_R4";
        if (in(protocol, R1_21_R5_MIN, R1_21_R5_MAX)) return "1_21_R5";
        if (in(protocol, R1_21_R6_MIN, R1_21_R6_MAX)) return "1_21_R6";
        // 1.21.10 shares R6 in Spigot; protocol may still be 773
        if (protocol == 773) return "1_21_R6";
        if (in(protocol, R1_21_R7_MIN, R1_21_R7_MAX)) return "1_21_R7";
        if (in(protocol, R26_1_MIN, R26_1_MAX)) return "26_1";
        if (protocol >= R26_2_MIN) return "26_2";
        return null;
    }

    private static boolean in(int protocol, int min, int max) {
        return protocol >= min && protocol <= max;
    }
